import express from 'express';
import { GoogleGenAI } from '@google/genai';

const router = express.Router();

// Simple in-memory rate limiter: tracks last request timestamp per client IP (1 request per 10 seconds / 6 req per min)
const rateLimitMap = new Map();

/**
 * Intelligent fallback generator when Gemini API key is unavailable or third-party service fails
 * Ensures seamless offline lab viva defense and graceful degradation.
 */
function generateContextualFallback(title, priority = 'medium') {
  const cleanTitle = title.trim();
  const lower = cleanTitle.toLowerCase();

  let details = '';
  if (lower.includes('docker') || lower.includes('container')) {
    details = 'Configure Dockerfile, define container ports, specify dependencies, and orchestrate with docker-compose.yml.';
  } else if (lower.includes('test') || lower.includes('jest') || lower.includes('ci')) {
    details = 'Set up test suites, verify API status codes (200, 201, 400, 404), and integrate automated GitHub Actions workflow.';
  } else if (lower.includes('auth') || lower.includes('jwt') || lower.includes('login')) {
    details = 'Implement bcrypt password hashing, sign JWT token with 1h expiration, and protect endpoints with bearer auth middleware.';
  } else if (lower.includes('cache') || lower.includes('performance')) {
    details = 'Implement in-memory node-cache caching for GET endpoints, invalidate on state mutations, and benchmark response times.';
  } else if (lower.includes('mongo') || lower.includes('database')) {
    details = 'Define Mongoose schema with schema validation, indexes, and connection string with environment variables.';
  } else if (lower.includes('react') || lower.includes('ui') || lower.includes('frontend')) {
    details = 'Develop modular React components, manage reactive state with useState/useEffect, and implement responsive CSS styling.';
  } else {
    details = `Execute and review all core engineering requirements for "${cleanTitle}". Ensure comprehensive test coverage and documentation.`;
  }

  return {
    description: `[Planned Objective]: ${cleanTitle}.\n\n[Action Items]:\n1. ${details}\n2. Perform local verification and error boundary checks.\n3. Validate output adherence to grading rubrics.`,
    suggestedPriority: lower.includes('bug') || lower.includes('fix') || lower.includes('critical') ? 'high' : priority,
    suggestedDeadline: new Date(Date.now() + 3 * 24 * 60 * 60 * 1000).toISOString().split('T')[0],
    source: 'fallback-heuristics',
    fallback: true,
    disclaimer: 'Generated via local offline heuristic model (Graceful Degradation Mode).',
  };
}

/**
 * POST /api/ai/generate-description
 * Generates an AI-suggested task description, priority, and milestone breakdown.
 */
router.post('/generate-description', async (req, res) => {
  const clientIp = req.ip || req.headers['x-forwarded-for'] || '127.0.0.1';
  const now = Date.now();

  // 1. Rate limiting check (Practical 13 Supplementary Problem)
  const lastCall = rateLimitMap.get(clientIp);
  if (lastCall && now - lastCall < 3000) {
    // 3 second debounce to prevent rapid spamming
    return res.status(429).json({
      error: 'Rate limit exceeded. Please wait a moment before requesting another AI suggestion.',
      retryAfter: Math.ceil((3000 - (now - lastCall)) / 1000),
    });
  }
  rateLimitMap.set(clientIp, now);

  const { title, priority } = req.body;

  if (!title || typeof title !== 'string' || !title.trim()) {
    return res.status(400).json({
      error: 'Task title is required to generate AI suggestion.',
    });
  }

  const apiKey = process.env.GEMINI_API_KEY || process.env.GOOGLE_API_KEY;

  // 2. If no API key configured, use graceful degradation immediately
  if (!apiKey || apiKey.trim() === 'your_gemini_api_key_here') {
    const fallbackResult = generateContextualFallback(title, priority);
    return res.status(200).json(fallbackResult);
  }

  // 3. Call Google Gemini API securely on the backend
  try {
    const ai = new GoogleGenAI({ apiKey });
    const prompt = `You are an expert technical project manager. Given the task title: "${title.trim()}", produce a concise, professional task description (2-3 sentences max) with actionable bullet points. Do not include markdown formatting or quotes.`;

    const response = await ai.models.generateContent({
      model: 'gemini-2.5-flash',
      contents: prompt,
    });

    const candidateText = response?.text?.trim() || '';

    if (!candidateText) {
      throw new Error('Empty response received from Gemini API');
    }

    return res.status(200).json({
      description: candidateText,
      suggestedPriority: priority || 'medium',
      suggestedDeadline: new Date(Date.now() + 3 * 24 * 60 * 60 * 1000).toISOString().split('T')[0],
      source: 'gemini-2.5-flash',
      fallback: false,
      disclaimer: 'AI-generated by Gemini API. Please review and customize before saving.',
    });
  } catch (err) {
    console.warn(`[AI SERVICE WARNING] Third-party AI call failed (${err.message}). Activating graceful degradation.`);
    // Practical 13: Handle API errors gracefully -> Return fallback message -> App keeps working
    const fallbackResult = generateContextualFallback(title, priority);
    return res.status(200).json({
      ...fallbackResult,
      serviceNotice: `Live AI service unavailable (${err.message}). Provided high-fidelity template.`,
    });
  }
});

export default router;
